package promptbuilder

// 记忆（user_memories）定义的唯一来源。
//
// 链路上有两处 prompt 需要知道「记忆是什么」，它们全部引用本常量，不得各写一份：
//   - 抽取段（post_chat）：agent/extractor.go 的 buildMemoryInstructionXML，按此定义从对话里捞候选
//   - 决策段（两入口）：agent/record_loop_types.go 的 system prompt，按此定义判断这条候选该怎么入库
//
// 主循环**不用**本常量：客户端常驻主循环看不到它，主循环只说「何时触发 record_memory」，定义
// 由该工具自己的说明与参数 schema 承担。历史上主循环准则 4 也内嵌过本常量，除了与工具说明重复，
// 还因常量内含空行把准则 4 劈出编号列表（见 docs/bugs/022）——已移除。
//
// 改定义只动这里。
const MemoryDefinition = `记忆是从对话里沉淀下来的、将来聊天还会用到的用户长期信息，包括：用户的决定与理由、
结论与洞察、观点与判断、偏好与习惯、状态与计划、人物关系、经验教训，以及用户分享的外部信息。

一条记忆 = 一件事（一个 topic + 一句 summary + 若干 facts 细节），不是一段对话的摘要。
topic 是一个主题词：非空、≤5 字、只含中英文数字、一个词，禁止斜杠/逗号/多主题。

以下不属于记忆：
- 逐日流水（睡眠打卡、体重、饮酒、运动、时间日志等按天读数）——属于文档台账。
- 单笔账目的录入与归类细节（某个小票怎么拆、某件商品归哪个二级分类）——属于账单数据本身。
- 只对本次任务成立的过程性内容：本轮产出形式、推进顺序、本轮临时口径、讨论中的中间结论。
- 已经写进文档/方案/代码的内容——文档才是它的家，记忆不重复承载。

判据一句话：这件事过一个月再看，还对了解用户本人有用吗？说不出用途的，不记。`
